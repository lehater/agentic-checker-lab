"""Exercise the architecture gate against the byte-identical archived RPG.

The original was generated by CoderMind in PR #27, not synthesized here.
Model invocation / native CoderMind pause-point integration are NOT tested.
"""
from __future__ import annotations

import copy
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
ARCHIVED = ROOT / "tests/fixtures/architecture/checker-v1-archived-skeleton.json"
CHECK = ROOT / "tools/check_architecture.py"
SOURCE_GIT_BLOB_SHA = "a6201115f9597f809aed60a83483bcb713e6acbc"


def gate(path: Path):
    p = subprocess.run([sys.executable, str(CHECK), "--contract",
                        str(ROOT / "docs/engineering/architecture-contract.json"),
                        "--skeleton", str(path), "--json"],
                       capture_output=True, text=True, check=False)
    return p.returncode, json.loads(p.stdout)


def git_blob_hash(blob: bytes) -> str:
    return hashlib.sha1(f"blob {len(blob)}\0".encode() + blob).hexdigest()


def corrected_skeleton(original: dict) -> dict:
    """A controlled path placement correction; NOT an AI-generated replan."""
    result = copy.deepcopy(original)
    package = result["root"]["children"][0]["children"][0]
    app = next(x for x in package["children"] if x.get("name") == "application")
    domain = next(x for x in package["children"] if x.get("name") == "domain")
    nested_app = next(x for x in domain["children"] if x.get("name") == "application")
    use_case = next(x for x in nested_app["children"] if x.get("name") == "check.py")
    use_case["path"] = "src/acl_checker/application/check.py"
    app["children"].append(use_case)
    domain["children"].remove(nested_app)
    return result


class ArchivedRpgGateTests(unittest.TestCase):
    def test_snapshot_is_exact_original_git_blob(self):
        self.assertEqual(git_blob_hash(ARCHIVED.read_bytes()), SOURCE_GIT_BLOB_SHA)

    def test_real_archived_rpg_rejected_before_codegen(self):
        rc, result = gate(ARCHIVED)
        self.assertEqual(rc, 1, result)
        self.assertEqual(result["status"], "FAIL")
        self.assertEqual(result["checked"]["skeleton_files"], 19)
        self.assertTrue(any("nested layer root" in x for x in result["violations"]), result)
        self.assertTrue(any("belongs in application" in x for x in result["violations"]), result)

    def test_same_rpg_with_fixed_ownership_passes_architecture_only(self):
        with tempfile.TemporaryDirectory() as folder:
            source = json.loads(ARCHIVED.read_text(encoding="utf-8"))
            fixed = Path(folder) / "fixed.json"
            fixed.write_text(json.dumps(corrected_skeleton(source), ensure_ascii=False),
                             encoding="utf-8")
            rc, result = gate(fixed)
            self.assertEqual(rc, 0, result)
            self.assertEqual(result["status"], "PASS")
            # This PASS means only structural/declared feature checks.
            # It says nothing about correct interfaces, generated code or product behavior.


if __name__ == "__main__":
    unittest.main()
