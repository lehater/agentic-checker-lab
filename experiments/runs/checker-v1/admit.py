"""Mechanical admission/publication for explicitly reviewed project artifacts.

Run from repository root: python3 experiments/runs/checker-v1/admit.py <slug>.
No semantic decisions or review verdicts are generated by this script.
"""
import copy
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import yaml

ROOT = Path.cwd()
RUN = ROOT / 'experiments/runs/checker-v1'
PACK = Path(subprocess.check_output(['python3', '.harness/harnessw.py', 'sync'], text=True).strip())
sys.path.insert(0, str(PACK / 'src'))
from harness.application.semantic_admission import admit_artifact
from harness.application.project_publication import (build_project_publication, read_project_publication,
    prepare_capability_transition, publish_project_publication)
from harness.application.decision_pipeline import derive_decision_roadmap
from harness.project_model.engineering_graph import validate_realization
from harness.reference_model.project_status import bootstrap_registry, validate_registry, status

def load(path):
    return yaml.safe_load(Path(path).read_text())

def save(path, data):
    Path(path).write_text(yaml.safe_dump(data, sort_keys=False, allow_unicode=True))

slug = sys.argv[1]
spec = load(RUN / (slug + '.yaml'))
policy_path = ROOT / '.harness/decision-policy.yaml'
policy = load(policy_path) if policy_path.exists() else None
gpath = ROOT / '.harness/engineering-graph.yaml'
graph = load(gpath)
cap = spec['candidate']['capability']
route = subprocess.check_output(['python3', '-m', 'harness.application.skill_router', 'artifact',
    '--knowledge-kind', spec['knowledge_kind'], '--root', str(PACK)], text=True,
    env=__import__('os').environ | {'PYTHONPATH': str(PACK / 'src')})
route = json.loads(route)
# Routing/hash evidence; the coordinator must read these before preparing the spec.
instructions = {rel: hashlib.sha256((PACK / rel).read_bytes()).hexdigest()
                for rel in [*route['instruction_contracts'], route['skill']]}
pubpath = ROOT / '.harness/project-publication.yaml'
if pubpath.exists():
    before = read_project_publication(pubpath, graph=graph)
else:
    model = dict(authorities=[dict(id=a['id']) for a in graph['authorities']], artifacts=[], questions=[])
    before = build_project_publication(graph=graph, core_model=model,
        semantic_evaluations=dict(version=1, kind='harness-semantic-evaluation-set', semantic_evaluations=[]),
        lifecycle=dict(version=1, kind='harness-capability-lifecycle', providers=[]))
    publish_project_publication(pubpath, graph=graph, publication=before, expected_revision=None)
s = copy.deepcopy(before['state'])
s['core_model']['authorities'] = [dict(id=a['id']) for a in graph['authorities']]
contracts = load(PACK / 'spec/semantic-acceptance/knowledge-kind-contracts-v1.yaml')
decisions = load(PACK / 'spec/decision-governance/knowledge-kind-decision-contracts-v1.yaml')
road = derive_decision_roadmap(graph=graph, model=s['core_model'], target='CHECKER-PROTOTYPE',
    lifecycle=s['lifecycle'], decision_contracts=decisions, decision_policy=policy,
    decision_failures=s['decision_failures'])
save(RUN / (slug + '-roadmap-before.yaml'), road)
sources = dict(semantic_assertions=[])
for artifact in s['core_model']['artifacts']:
    if artifact['id'] not in spec.get('depends_on', []):
        continue
    prior = load(RUN / (artifact['id'] + '.yaml'))
    sources['semantic_assertions'].extend(dict(a, source_artifact=artifact['id'])
        for a in prior['candidate']['semantic_assertions'])
candidate = spec['candidate']
identity = dict(spec=spec, content_sha256=hashlib.sha256((ROOT/candidate['path']).read_bytes()).hexdigest(),
                instructions=instructions, pin=PACK.name)
acceptance_id = 'checker-v1-' + hashlib.sha256(json.dumps(identity, sort_keys=True).encode()).hexdigest()[:24]
ev = admit_artifact(graph=graph, model=s['core_model'],
    skill_registry=load(PACK / 'skills/artifact-skill-registry-v0.yaml'),
    knowledge_contracts=contracts, decision_contracts=decisions, capability=cap,
    candidate=candidate, sources=sources, acceptance_id=acceptance_id, lifecycle=s['lifecycle'],
    decision_exploration=spec.get('decision_exploration'), decision_policy=policy)
save(RUN / (slug + '-admission.yaml'), ev)
if ev['status'] != 'ACCEPTED':
    print(json.dumps(ev, ensure_ascii=False, indent=2))
    raise SystemExit(1)
row = dict(id=candidate['id'], authority=ev['admission']['authority'], path=candidate['path'],
           provides=[cap], depends_on=spec.get('depends_on', []))
s['core_model']['artifacts'] = [a for a in s['core_model']['artifacts'] if a['id'] != row['id']] + [row]
s['semantic_evaluations']['semantic_evaluations'] = [e for e in s['semantic_evaluations']['semantic_evaluations']
    if e['capability'] != cap] + [ev]
s['lifecycle']['providers'] = [p for p in s['lifecycle']['providers'] if p['capability'] != cap] + [ev['lifecycle_assertion']]
nextpub = prepare_capability_transition(graph=graph, current_publication=before,
    expected_revision=before['revision'], capability=cap, outcome='CURRENT', **s)
if nextpub != before:
    publish_project_publication(pubpath, graph=graph, publication=nextpub, expected_revision=before['revision'])
assert read_project_publication(pubpath, graph=graph) == nextpub
catalog = load(PACK / 'catalogs/software-authorities-v0.yaml')
registry = bootstrap_registry(catalog, core=s['core_model'])
assert not validate_registry(catalog, registry)
save(ROOT / '.harness/authority-assessments.yaml', registry)
save(RUN / 'authority-status.yaml', status(catalog, registry, s['core_model']))
save(RUN / (slug + '-publication.yaml'), nextpub)
save(RUN / (slug + '-evidence.yaml'), dict(pin=PACK.name, instructions=instructions,
    content_sha256=identity['content_sha256'], publication_revision=nextpub['revision'],
    status=ev['status'], acceptance_id=acceptance_id))
print(cap, 'CURRENT', nextpub['revision'])
